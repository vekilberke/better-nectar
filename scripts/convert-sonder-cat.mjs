// Converts SondeR cat pixel grids (third_party/sonder-cat/sprites.py, Apache-2.0,
// by Verisonder) into src/components/sonderCatData.ts. Re-run: node scripts/convert-sonder-cat.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "third_party/sonder-cat/sprites.py"), "utf8");

const USED = ["sit_a", "sit_b", "blink", "sleep", "run_a", "run_b", "stretch", "yawn", "groom_a", "groom_b", "type_a", "type_b", "peek", "knead_a", "knead_b", "knead_c", "meow"];
const SOLID = new Set("KBSWEZNMGg");
// Named characters are the author's marks (NOTICE); only the generic coat colours are used.
const SKIP_PALETTES = new Set(["mimi", "jj", "lilly"]);
const EXTRA = { O: "#ffffff", H: "#f2f4f6", G: "#8a8f98", g: "#d4d8de" };

// Nectar's changes to SondeR frames: meow is sit_a with the mouth open (dark rim, pink tongue).
const DERIVED = {
  meow: { from: "sit_a", eyes: "sit_a", note: "an open mouth", cells: [[11, 10, "MMMM"], [12, 10, "MNNM"], [13, 11, "MM"]] },
};

function grid(name) {
  const d = DERIVED[name];
  if (d) {
    const rows = grid(d.from);
    for (const [y, x, cells] of d.cells) rows[y] = rows[y].slice(0, x) + cells + rows[y].slice(x + cells.length);
    return rows;
  }
  const m = src.match(new RegExp("^" + name.toUpperCase() + " = \\[([\\s\\S]*?)^\\]", "m"));
  if (!m) throw new Error(`frame ${name} not found`);
  return [...m[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]);
}

function halo(rows) {
  const h = rows.length, w = rows[0].length;
  return rows.map((row, y) => [...row].map((c, x) => {
    if (c !== ".") return c;
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
      const r = rows[y + dy]?.[x + dx];
      if (r && SOLID.has(r)) return "O";
    }
    return ".";
  }).join(""));
}

// Blank rows on top leave room to shift a taller frame (stretch) up onto the sit baseline.
const PAD = 2;
const frames = Object.fromEntries(USED.map((n) => {
  const rows = halo(grid(n));
  return [n, [...Array(PAD).fill(".".repeat(rows[0].length)), ...rows]];
}));

// Bottom-align every frame (up or down) to the sit frame so the cat does not hop when it starts running.
const bottomRow = (rows) => rows.reduce((b, r, y) => (/[^.]/.test(r) ? y : b), 0);
const SIT_BOTTOM = bottomRow(frames.sit_a);
const shifts = {};
for (const n of USED) {
  const d = SIT_BOTTOM - bottomRow(frames[n]);
  shifts[n] = d + PAD;
  const blank = ".".repeat(frames[n][0].length);
  if (d > 0) frames[n] = [...Array(d).fill(blank), ...frames[n].slice(0, frames[n].length - d)];
  if (d < 0) {
    if (frames[n].slice(0, -d).some((r) => /[^.]/.test(r))) throw new Error(`frame ${n} cannot shift up by ${-d}`);
    frames[n] = [...frames[n].slice(-d), ...Array(-d).fill(blank)];
  }
}
const GRID_W = frames.sit_a[0].length, GRID_H = frames.sit_a.length;

let x0 = GRID_W, y0 = GRID_H, x1 = 0, y1 = 0;
for (const rows of Object.values(frames)) rows.forEach((row, y) => [...row].forEach((c, x) => {
  if (c === ".") return;
  x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
}));
const W = x1 - x0 + 1, H = y1 - y0 + 1;

function layers(rows) {
  const by = {};
  rows.slice(y0, y1 + 1).forEach((full, y) => {
    const row = full.slice(x0, x1 + 1);
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c === ".") { x++; continue; }
      let e = x;
      while (e < row.length && row[e] === c) e++;
      by[c] = (by[c] ?? "") + `M${x} ${y}h${e - x}v1h${x - e}z`;
      x = e;
    }
  });
  return by;
}

const eyeBlock = src.match(/^EYE_CELLS = \{([\s\S]*?)^\}/m)[1];
const eyes = {};
for (const m of eyeBlock.matchAll(/"(\w+)":\s*\[\(([\d, ()]+)\)\]/g)) {
  if (!USED.includes(m[1])) continue;
  eyes[m[1]] = [...m[2].matchAll(/(\d+),\s*(\d+)/g)].map((p) => [Number(p[1]) - x0, Number(p[2]) + (shifts[m[1]] ?? 0) - y0]);
}
for (const [n, d] of Object.entries(DERIVED)) if (eyes[d.eyes]) eyes[n] = eyes[d.eyes];

const palBlock = src.match(/^PALETTES = \{([\s\S]*?)^\}/m)[1];
const palettes = {};
for (const m of palBlock.matchAll(/"([^"]+)":\s*\{([^}]*)\}/g)) {
  if (SKIP_PALETTES.has(m[1])) continue;
  const p = { ...EXTRA };
  for (const c of m[2].matchAll(/"(\w)":\s*"(#[0-9a-fA-F]{6})"/g)) p[c[1]] = c[2];
  palettes[m[1]] = p;
}

const out = {
  W, H,
  frames: Object.fromEntries(USED.map((n) => [n, layers(frames[n])])),
  eyes,
  palettes,
};

writeFileSync(
  join(root, "src/components/sonderCatData.ts"),
  `// Generated by scripts/convert-sonder-cat.mjs from SondeR cat by Verisonder (Apache-2.0). Do not edit.\n` +
  `// Modified by Nectar: pixel grids turned into SVG paths with a white outline and aligned to the sit frame; ` +
  `${Object.entries(DERIVED).map(([n, d]) => `new ${n} frame = ${d.from} with ${d.note}`).join("; ")}.\n` +
  `export const CAT_W = ${W};\nexport const CAT_H = ${H};\n` +
  `export const CAT_FRAMES: Record<string, Record<string, string>> = ${JSON.stringify(out.frames)};\n` +
  `export const CAT_EYES: Record<string, [number, number][]> = ${JSON.stringify(eyes)};\n` +
  `export const CAT_PALETTE_NAMES = ${JSON.stringify(Object.keys(palettes))};
export const CAT_PALETTES: Record<string, Record<string, string>> = ${JSON.stringify(palettes)};\n`
);
console.log(`ok ${W}x${H}, ${Object.keys(palettes).length} palettes, eyes: ${Object.keys(eyes).join(",")}`);
