// Writes THIRD_PARTY_LICENSES.md: every Rust crate built into the shared exe (cargo metadata,
// default features, Windows x64) and every npm package bundled into the frontend (production
// dependencies), grouped by licence text. Needs `cargo` on PATH and `node_modules` installed.
//
//   node scripts/third-party-licenses.mjs [--out THIRD_PARTY_LICENSES.md]
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

function licenseTexts(dir) {
  if (!dir || !existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => LICENSE_FILE.test(name))
    .sort()
    .map((name) => readFileSync(join(dir, name), "utf8").replace(/\r\n/g, "\n").trim())
    .filter(Boolean);
}

function rustPackages() {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-gnullvm"], {
      cwd: join(root, "src-tauri"),
      maxBuffer: 256 * 1024 * 1024,
    }).toString(),
  );
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const stack = [meta.resolve.root];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      // Normal dependencies only: build scripts and dev tools are not shipped.
      if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
    }
  }
  seen.delete(meta.resolve.root);
  return [...seen].map((id) => byId.get(id)).filter(Boolean).map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? `see ${p.license_file}` : "unknown"),
    url: p.repository ?? p.homepage ?? `https://crates.io/crates/${p.name}`,
    texts: licenseTexts(dirname(p.manifest_path)),
  }));
}

function npmPackages() {
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const seen = new Map();
  const stack = Object.keys(pkg.dependencies ?? {});
  while (stack.length) {
    const name = stack.pop();
    if (seen.has(name)) continue;
    const dir = join(root, "node_modules", name);
    const file = join(dir, "package.json");
    if (!existsSync(file)) continue;
    const meta = JSON.parse(readFileSync(file, "utf8"));
    seen.set(name, {
      name,
      version: meta.version,
      license: typeof meta.license === "string" ? meta.license : meta.license?.type ?? "unknown",
      url: typeof meta.repository === "string" ? meta.repository : meta.repository?.url ?? `https://www.npmjs.com/package/${name}`,
      texts: licenseTexts(dir),
    });
    stack.push(...Object.keys(meta.dependencies ?? {}));
  }
  return [...seen.values()];
}

function section(title, packages) {
  packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  const groups = new Map();
  for (const p of packages) {
    const text = p.texts.join("\n\n---\n\n");
    const key = text ? createHash("sha256").update(text).digest("hex") : `none:${p.license}`;
    if (!groups.has(key)) groups.set(key, { text, license: p.license, members: [] });
    groups.get(key).members.push(p);
  }
  const lines = [`## ${title}`, "", "| Package | Version | Licence |", "|---|---|---|"];
  for (const p of packages) lines.push(`| [${p.name}](${p.url.replace(/^git\+/, "")}) | ${p.version} | ${p.license} |`);
  lines.push("", `### Licence texts (${title})`, "");
  for (const group of groups.values()) {
    lines.push(`#### ${group.members.map((m) => `${m.name} ${m.version}`).join(", ")}`, "");
    if (group.text) lines.push("```text", group.text.replace(/```/g, "'''"), "```", "");
    else lines.push(`No licence file in the package; its metadata says \`${group.license}\`.`, "");
  }
  return lines.join("\n");
}

const out = resolve(root, process.argv.includes("--out") ? process.argv[process.argv.indexOf("--out") + 1] : "THIRD_PARTY_LICENSES.md");
const doc = [
  "# Third-party licences",
  "",
  "Better Nectar is GPL-3.0-only (see `LICENSE` and `NOTICE`). The release binary and installer also contain the",
  "components below under their own licences. Generated by `scripts/third-party-licenses.mjs`; do not edit by hand.",
  "",
  "## Microsoft WebView2 loader",
  "",
  "`WebView2Loader.dll` is installed next to the exe. It is Microsoft's WebView2 SDK loader, taken from the",
  "`webview2-com-sys` crate (which redistributes it from the `Microsoft.Web.WebView2` NuGet package) and used under",
  "the WebView2 SDK licence: https://www.nuget.org/packages/Microsoft.Web.WebView2/ (License). Copyright (C) Microsoft",
  "Corporation.",
  "",
  "## SondeR cat",
  "",
  "The pixel cat is based on SondeR cat by Verisonder (Apache-2.0); see `third_party/sonder-cat/LICENSE` and `NOTICE`.",
  "",
  section("Rust crates", rustPackages()),
  "",
  section("npm packages", npmPackages()),
  "",
].join("\n");
writeFileSync(out, doc);
console.log(`wrote ${out}`);
